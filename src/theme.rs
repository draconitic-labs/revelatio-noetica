    v.widgets.active.bg_stroke = Stroke::new(1.0, LIGHT);
    v.widgets.active.fg_stroke = Stroke::new(1.0, LIGHT);
    v.widgets.open.bg_fill = EDGE;
    v.widgets.open.weak_bg_fill = PRESS;
    v.widgets.open.bg_stroke = Stroke::new(1.0, DUSK);
    v.widgets.open.fg_stroke = Stroke::new(1.0, LIGHT);
    v.slider_trailing_fill = true;
