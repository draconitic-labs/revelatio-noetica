#!/usr/bin/env bash
# Renders assets/math/manifest.txt to white-on-transparent PNGs in assets/math/
# and regenerates src/mathimg_gen.rs, which bakes them into the binary. The app
# uses each PNG's alpha as a mask and tints it to the theme's text colour.
#
# Needs pdflatex (with amsmath, amssymb, xcolor, preview) and pdftocairo:
#   Fedora: sudo dnf install texlive-scheme-basic texlive-preview poppler-utils
#   Debian/Ubuntu: sudo apt install texlive-latex-extra poppler-utils
set -euo pipefail

proj="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
manifest="$proj/assets/math/manifest.txt"
outdir="$proj/assets/math"
gen="$proj/src/mathimg_gen.rs"
dpi=600

for tool in pdflatex pdftocairo; do
    command -v "$tool" >/dev/null || { echo "render_math: $tool not found" >&2; exit 1; }
done

work="$(mktemp -d)"
trap 'rm -rf -- "$work"' EXIT

keys=()
failed=0
while IFS= read -r line || [[ -n "$line" ]]; do
    [[ -z "${line// /}" || "$line" == \#* ]] && continue
    key="${line%%=*}"
    key="${key//[[:space:]]/}"
    body="${line#*=}"
    body="${body#"${body%%[![:space:]]*}"}"
    name="${key//./_}"
    {
        printf '%s\n' '\documentclass{article}' \
            '\usepackage[active,tightpage]{preview}' \
            '\usepackage{amsmath,amssymb}' \
            '\usepackage{xcolor}' \
            '\pagestyle{empty}' \
            '\begin{document}' \
            '\begin{preview}'
        printf '%s\n' "\\color{white}\$\\displaystyle $body\$"
        printf '%s\n' '\end{preview}' '\end{document}'
    } >"$work/$name.tex"
    if (cd "$work" && pdflatex -interaction=nonstopmode -halt-on-error "$name.tex" >/dev/null 2>&1) \
        && pdftocairo -png -transp -singlefile -r "$dpi" "$work/$name.pdf" "$work/$name"; then
        cp "$work/$name.png" "$outdir/$name.png"
        keys+=("$key")
        echo "ok   $key"
    else
        echo "FAILED  $key" >&2
        failed=$((failed + 1))
    fi
done <"$manifest"

if ((failed > 0)); then
    echo "render_math: $failed formula(s) failed; src/mathimg_gen.rs left unchanged" >&2
    exit 1
fi

{
    echo '// Generated by tools/render_math.sh - do not edit.'
    echo 'pub static MATH_PNGS: &[(&str, &[u8])] = &['
    for key in "${keys[@]}"; do
        printf '    ("%s", include_bytes!("../assets/math/%s.png")),\n' "$key" "${key//./_}"
    done
    echo '];'
} >"$gen"
echo "rendered ${#keys[@]} formulas; regenerated src/mathimg_gen.rs"
