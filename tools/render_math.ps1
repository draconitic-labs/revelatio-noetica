# Windows counterpart of tools/render_math.sh. The app uses only the alpha of each
# PNG, sized for 600 dpi, so the ink colour below does not matter.
# Renders assets/math/manifest.txt formulas via LaTeX -> dvipng -> transparent
# PNGs in assets/math/, then generates src/mathimg_gen.rs embedding them.
$ErrorActionPreference = "Stop"
$proj = Split-Path $PSScriptRoot -Parent
$mik = "$env:LOCALAPPDATA\Programs\MiKTeX\miktex\bin\x64"
if (-not (Test-Path "$mik\latex.exe")) { $mik = "C:\Program Files\MiKTeX\miktex\bin\x64" }
$env:Path = "$mik;$env:Path"
& initexmf --set-config-value "[MPM]AutoInstall=1" 2>$null | Out-Null

$work = Join-Path $env:TEMP "rn_math_build"
New-Item -ItemType Directory -Force $work | Out-Null
$outdir = Join-Path $proj "assets\math"
$keys = @()

Get-Content (Join-Path $outdir "manifest.txt") | ForEach-Object {
    $line = $_.Trim()
    if ($line -eq "" -or $line.StartsWith("#")) { return }
    $idx = $line.IndexOf("=")
    $key = $line.Substring(0, $idx).Trim()
    $texbody = $line.Substring($idx + 1).Trim()
    $fname = $key -replace "\.", "_"
    $tex = @"
\documentclass{article}
\usepackage[active,tightpage]{preview}
\usepackage{amsmath,amssymb}
\usepackage{xcolor}
\pagestyle{empty}
\begin{document}
\begin{preview}
\color[RGB]{34,38,50}`$\displaystyle $texbody`$
\end{preview}
\end{document}
"@
    Set-Content -Path (Join-Path $work "$fname.tex") -Value $tex -Encoding ascii
    Push-Location $work
    & latex -interaction=nonstopmode "$fname.tex" | Out-Null
    if (Test-Path "$fname.dvi") {
        & dvipng -q -D 600 -T tight -bg Transparent -o "$fname.png" "$fname.dvi" | Out-Null
        if (Test-Path "$fname.png") {
            Copy-Item "$fname.png" (Join-Path $outdir "$fname.png") -Force
            $script:keys += $key
            Write-Host "ok   $key"
        } else { Write-Host "PNG FAILED  $key" }
    } else { Write-Host "TEX FAILED  $key" }
    Pop-Location
}

# Generate the Rust embed.
$gen = "// Generated by tools/render_math.ps1 - do not edit.`n"
$gen += "pub static MATH_PNGS: &[(&str, &[u8])] = &[`n"
foreach ($k in $keys) {
    $f = $k -replace "\.", "_"
    $gen += "    (`"$k`", include_bytes!(`"../assets/math/$f.png`")),`n"
}
$gen += "];`n"
Set-Content -Path (Join-Path $proj "src\mathimg_gen.rs") -Value $gen -Encoding ascii
Write-Host "rendered $($keys.Count) formulas; generated src/mathimg_gen.rs"
